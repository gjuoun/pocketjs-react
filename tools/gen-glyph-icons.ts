// Generates src/primitives/glyph-icons.gen.tsx: one component per lucide export (canonical icons and
// aliases) that draws the icon's baked 16 px variant. The six exports glyph-icons.tsx writes by hand are
// skipped. The committed module must match this generator (--check fails on drift).
//
//   bun tools/gen-glyph-icons.ts          write the module
//   bun tools/gen-glyph-icons.ts --check  exit 1 when the committed module is stale

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { lucideIcons } from "./icon-bake.ts";

const OUT = join(import.meta.dir, "../src/primitives/glyph-icons.gen.tsx");

/** The exports glyph-icons.tsx writes by hand. */
const HAND_WRITTEN = new Set(["XIcon", "CheckIcon", "CircleIcon", "ChevronDownIcon", "ChevronUpIcon", "ChevronRightIcon"]);

/** lucide's export name for an icon name: grid-2x2 -> Grid2x2Icon. */
export function exportName(name: string): string {
  return name.split("-").map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("") + "Icon";
}

/** The module text: one component per export, sorted by export name, each drawing its canonical icon. */
export async function generate(): Promise<string> {
  const byExport = new Map<string, string>();
  for (const icon of await lucideIcons()) {
    for (const name of [icon.name, ...icon.aliases]) {
      const ex = exportName(name);
      if (HAND_WRITTEN.has(ex)) continue;
      const prev = byExport.get(ex);
      if (prev !== undefined && prev !== icon.name)
        throw new Error("gen-glyph-icons: " + ex + " maps to both " + prev + " and " + icon.name);
      byExport.set(ex, icon.name);
    }
  }
  const header = [
    "// Generated by tools/gen-glyph-icons.ts from the lucide-react icon set. Do not edit: run",
    "// `bun tools/gen-glyph-icons.ts`. Each export draws the icon's baked 16 px variant (see glyph-icon.tsx).",
    "",
    'import { GlyphIcon, type GlyphProps } from "./glyph-icon.tsx";',
    "",
  ].join("\n");
  const body = [...byExport]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([ex, icon]) => 'export function ' + ex + '(props: GlyphProps) {\n  return <GlyphIcon {...props} name="' + icon + '" px={16} char="?" />;\n}\n')
    .join("\n");
  return header + "\n" + body;
}

if (import.meta.main) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    let committed = "";
    try {
      committed = readFileSync(OUT, "utf8");
    } catch {}
    if (committed !== text) {
      console.error("stale: " + OUT + " (run bun tools/gen-glyph-icons.ts)");
      process.exit(1);
    }
    console.log("ok: " + OUT);
  } else {
    writeFileSync(OUT, text);
    console.log("wrote " + OUT + " (" + text.split("\n").filter((l) => l.startsWith("export function")).length + " exports)");
  }
}
